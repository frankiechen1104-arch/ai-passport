#!/usr/bin/env python3
"""Rebuild original RGB565+A8 layered artwork and the fixed offline font subset.

Build dependencies: Pillow 12.3.0, fontTools 4.61.1, CairoSVG 2.8.2,
lv_font_conv 1.5.3. Runtime firmware requires none of these tools.
"""
from __future__ import annotations
import argparse
import hashlib
import io
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]

def inventory() -> str:
    symbols = set(chr(cp) for cp in range(32, 127))
    for name in ("poetry_corpus.c", "poetry_ui.c", "poetry_app.c"):
        source = (ROOT / "main" / name).read_text()
        for match in re.findall(r'"(?:[^"\\]|\\.)*"', source):
            text = json.loads(match)
            symbols.update(c for c in text if ord(c) >= 32)
    return "".join(sorted(symbols, key=ord))

def image_source() -> str:
    import cairosvg
    from PIL import Image
    parts = ['/* Generated by tools/generate_poetry_assets.py; original art: MIT. */',
             '#include "lvgl.h"', '#include "poetry_assets.h"']
    for name in ("otter", "foot", "ripple"):
        path = ROOT / "assets/images" / f"poetry_{name}.svg"
        im = Image.open(io.BytesIO(cairosvg.svg2png(url=str(path), scale=3))).convert("RGBA")
        im = im.resize((int(im.width / 3), int(im.height / 3)), Image.Resampling.LANCZOS)
        rgb, alpha = bytearray(), bytearray()
        for r, g, b, a in im.get_flattened_data():
            value = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            rgb.extend((value & 255, value >> 8)); alpha.append(a)
        # LVGL RGB565A8 stores a contiguous RGB565 plane then an A8 plane.
        data = rgb + alpha
        parts.append(f'static const uint8_t {name}_pixels[] = {{')
        for offset in range(0, len(data), 24):
            parts.append("    " + ",".join(f"0x{x:02x}" for x in data[offset:offset+24]) + ",")
        parts.extend(['};', f'const lv_image_dsc_t poetry_{name} = {{',
                      f'    .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8,',
                      f'        .w = {im.width}, .h = {im.height}, .stride = {im.width * 2} }},',
                      f'    .data_size = sizeof({name}_pixels), .data = {name}_pixels,', '};'])
    chars = inventory()
    parts.append('const char poetry_font_inventory[] = ' + json.dumps(chars, ensure_ascii=False) + ';')
    return "\n".join(parts) + "\n"

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", help="Licensed NotoSansCJK-Regular.ttc source, SC face index 2")
    parser.add_argument("--converter", default="work/font-tools/node_modules/.bin/lv_font_conv")
    parser.add_argument("--check", action="store_true", help="verify inventory, source hashes, and image byte parity")
    args = parser.parse_args()
    asset = ROOT / "assets/images/poetry_assets.c"
    chars_path = ROOT / "assets/fonts/poetry_symbols.txt"
    manifest_path = ROOT / "assets/fonts/poetry_assets.json"
    font_path = ROOT / "assets/fonts/poetry_font_16.c"
    sources = [ROOT / "assets/images" / f"poetry_{n}.svg" for n in ("otter", "foot", "ripple")]
    sources += [font_path, ROOT / "assets/fonts/PoetrySubset-Regular.otf", chars_path, asset]
    if args.check:
        assert chars_path.read_text() == inventory(), "font inventory is stale"
        manifest = json.loads(manifest_path.read_text())
        for p in sources:
            assert hashlib.sha256(p.read_bytes()).hexdigest() == manifest["sha256"][str(p.relative_to(ROOT))], f"stale asset: {p}"
        assert asset.read_text() == image_source(), "layered RGB565+A8 bytes differ from original artwork"
        print(f"Poetry assets: PASS ({len(inventory())} printable glyphs)")
        return
    if not args.font:
        parser.error("--font is required for generation")
    from fontTools.ttLib import TTFont
    from fontTools import subset
    font = TTFont(args.font, fontNumber=2)
    chars = inventory()
    missing = set(map(ord, chars)) - font.getBestCmap().keys()
    assert not missing, f"missing source glyphs: {missing}"
    options = subset.Options()
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
    sub = subset.Subsetter(options=options)
    sub.populate(text=chars); sub.subset(font)
    for record in font["name"].names:
        if record.nameID in (1, 3, 4, 6):
            value = "PoetrySubset-Regular" if record.nameID == 6 else "Poetry Subset Regular"
            record.string = value.encode(record.getEncoding())
    font_dir = ROOT / "assets/fonts"
    font_dir.mkdir(parents=True, exist_ok=True)
    otf = font_dir / "PoetrySubset-Regular.otf"
    font.save(otf)
    chars_path.write_text(chars)
    subprocess.run([str(ROOT / args.converter), "--font", str(otf), "--symbols", chars,
        "--size", "16", "--bpp", "4", "--format", "lvgl", "--no-compress", "--no-kerning",
        "--lv-font-name", "poetry_font_16", "--lv-include", "lvgl.h", "--output", str(font_path)], check=True)
    # Converter embeds absolute invocation paths in comments; normalize only that
    # comment for reproducibility and retain all generated data unchanged.
    text = font_path.read_text()
    text = re.sub(r" \* Opts:.*", " * Opts: tools/generate_poetry_assets.py; lv_font_conv 1.5.3; 16px 4bpp plain", text)
    font_path.write_text(text)
    asset.write_text(image_source())
    manifest = {"converter": "lv_font_conv 1.5.3", "font_size": 16, "bpp": 4,
                "glyphs": len(chars), "corpus_version": 1,
                "sha256": {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in sources}}
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"Generated {len(chars)} glyphs and three original layered sprites")

if __name__ == "__main__":
    main()
