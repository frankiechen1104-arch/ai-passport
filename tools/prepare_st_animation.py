#!/usr/bin/env python3
"""Pack reviewed animation atlases at one shared origin/scale into Flash images."""
from pathlib import Path
from PIL import Image
import numpy as np
from scipy import ndimage
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'assets/images/st_otter/animation'
OUT.mkdir(exist_ok=True)
source=['/* Generated by tools/prepare_st_animation.py; mapped RGB565+A8. */','#include "st_animation_art.h"']
header=['#pragma once','#include "lvgl.h"','#define ST_ANIMATION_FRAMES 12','#define ST_ANIMATION_OUTFITS 6','extern const lv_image_dsc_t *const st_animation_frames[6][12];']
for outfit in range(6):
    atlas=Image.open(OUT/f'outfit_{outfit}_atlas.png').convert('RGBA')
    # The illustrator's row baselines can vary by a few pixels. Isolate the
    # three connected silhouettes in each column rather than cutting through feet.
    poses={}
    for col in range(4):
        left,right=round(col*atlas.width/4),round((col+1)*atlas.width/4)
        pixels=np.array(atlas.crop((left,0,right,atlas.height)))
        labels,count=ndimage.label(pixels[:,:,3]>64)
        areas=np.bincount(labels.ravel());areas[0]=0
        ids=sorted(np.argsort(areas)[-3:],key=lambda n:np.nonzero(labels==n)[0].min())
        for row,index in enumerate(ids):
            if areas[index]<2000:raise ValueError('Missing connected character silhouette')
            keep=ndimage.binary_dilation(labels==index,iterations=2)
            rgba=pixels.copy();rgba[:,:,3][~keep]=0
            im=Image.fromarray(rgba);bounds=im.getchannel('A').getbbox()
            poses[row*4+col]=(im,bounds)
    crop_left=min(b[0] for im,b in poses.values());crop_right=max(b[2] for im,b in poses.values())
    width=crop_right-crop_left;height=max(b[3]-b[1] for im,b in poses.values())
    ratio=min(124/width,160/height);size=(round(width*ratio),round(height*ratio))
    tiles=[im.crop((crop_left,b[3]-height,crop_right,b[3])) for im,b in (poses[i] for i in range(12))]
    data=bytearray()
    for frame,tile in enumerate(tiles):
        fitted=tile.resize(size,Image.Resampling.LANCZOS)
        canvas=Image.new('RGBA',(128,164));canvas.alpha_composite(fitted,((128-size[0])//2,164-size[1]))
        canvas.save(OUT/f'outfit_{outfit}_frame_{frame}.png')
        for r,g,b in canvas.convert('RGB').getdata():
            pixel=((r>>3)<<11)|((g>>2)<<5)|(b>>3);data.extend((pixel&255,pixel>>8))
        data.extend(canvas.getchannel('A').tobytes())
    (OUT/f'motion_{outfit}.raw').write_bytes(data)
    symbol=f'_binary_motion_{outfit}_raw_start'
    source.append(f'extern const uint8_t {symbol}[];')
    for frame in range(12):
        source.append(f'static const lv_image_dsc_t outfit_{outfit}_frame_{frame} = {{ .header={{.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_RGB565A8,.w=128,.h=164,.stride=256}}, .data_size=62976, .data={symbol}+{frame*62976} }};')
source.append('const lv_image_dsc_t *const st_animation_frames[6][12] = {'+','.join('{'+','.join(f'&outfit_{o}_frame_{f}' for f in range(12))+'}' for o in range(6))+'};')
(OUT/'st_animation_art.h').write_text('\n'.join(header)+'\n')
(OUT/'st_animation_art.c').write_text('\n'.join(source)+'\n')
print('72 frames, 6 outfits, 12 poses each; 4,534,272 mapped Flash bytes')
