#!/usr/bin/env python3
"""Convert reviewed ST atlas cells to mapped RGB565 and RGB565+A8 resources."""
from pathlib import Path
from PIL import Image,ImageOps
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'assets/images/st_otter'
def rgb565(im):
    data=bytearray()
    for r,g,b in im.convert('RGB').getdata():
        value=((r>>3)<<11)|((g>>2)<<5)|(b>>3)
        data.extend((value&255,value>>8))
    return data
background=Image.open(OUT/'travel_atlas.png')
character=Image.open(OUT/'outfit_atlas.png').convert('RGBA')
headers=['#pragma once','#include "lvgl.h"','extern const lv_image_dsc_t *const st_backgrounds[8];','extern const lv_image_dsc_t *const st_outfit_images[6];']
source=['/* Generated by tools/prepare_st_art.py; see assets README for provenance. */','#include "st_art.h"']
for kind,atlas,cols,rows,count,size in [('background',background,4,2,8,(240,320)),('outfit',character,3,2,6,(128,164))]:
    for i in range(count):
        col,row=i%cols,i//cols
        tile=atlas.crop((round(col*atlas.width/cols),round(row*atlas.height/rows),round((col+1)*atlas.width/cols),round((row+1)*atlas.height/rows)))
        if kind=='outfit':
            # Crop transparent margins only; retain every fin, hand and tail.
            bounds=tile.getchannel('A').getbbox()
            if not bounds:raise ValueError('Empty sprite')
            tile=tile.crop(bounds)
            fitted=ImageOps.contain(tile,(124,160),Image.Resampling.LANCZOS)
            tile=Image.new('RGBA',size);tile.alpha_composite(fitted,((128-fitted.width)//2,(164-fitted.height)//2))
        else:tile=tile.resize(size,Image.Resampling.LANCZOS)
        tile.save(OUT/f'{kind}_{i}.png')
        name=f'{kind}_{i}.raw';data=rgb565(tile)
        if kind=='outfit':data.extend(tile.getchannel('A').tobytes())
        (OUT/name).write_bytes(data)
        symbol=f'_binary_{kind}_{i}_raw_start'
        source.append(f'extern const uint8_t {symbol}[];')
        cf='LV_COLOR_FORMAT_RGB565A8' if kind=='outfit' else 'LV_COLOR_FORMAT_RGB565'
        source.append(f'static const lv_image_dsc_t {kind}_{i} = {{ .header={{.magic=LV_IMAGE_HEADER_MAGIC,.cf={cf},.w={size[0]},.h={size[1]},.stride={size[0]*2}}}, .data_size={len(data)}, .data={symbol} }};')
    source.append(f'const lv_image_dsc_t *const st_{"backgrounds" if kind=="background" else "outfit_images"}[{count}] = {{'+','.join(f'&{kind}_{i}' for i in range(count))+'};')
(OUT/'st_art.h').write_text('\n'.join(headers)+'\n');(OUT/'st_art.c').write_text('\n'.join(source)+'\n')
print('8 backgrounds; 6 complete fish-hood outfits; 1,606,656 mapped asset bytes')
