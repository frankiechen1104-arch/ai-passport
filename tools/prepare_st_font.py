#!/usr/bin/env python3
"""Reproducible uncompressed LVGL 4-bpp subset from Noto Sans CJK SC (OFL)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont
import json
ROOT=Path(__file__).resolve().parents[1]
font_path=ROOT/'assets/fonts/NotoSansCJKsc-Regular.otf'
source=''.join(p.read_text() for p in (ROOT/'main').glob('st_*.c'))+(ROOT/'main/main.c').read_text()
points=sorted(set(range(32,127)) | {ord(c) for c in source if ord(c)>127})
font=ImageFont.truetype(str(font_path),16)
cmap=TTFont(font_path).getBestCmap()
missing=[p for p in points if p not in cmap]
if missing: raise SystemExit(f'Missing source glyphs: {missing}')
bitmap=bytearray();descriptors=['{0,0,0,0,0,0}']
for p in points:
    c=chr(p);left,top,right,bottom=font.getbbox(c,anchor='ls');w,h=right-left,bottom-top
    mask=Image.new('L',(max(1,w),max(1,h)));ImageDraw.Draw(mask).text((-left,-top),c,font=font,fill=255,anchor='ls')
    index=len(bitmap)
    values=[(v*15+127)//255 for v in mask.getdata()] if w and h else []
    if len(values)%2:values.append(0)
    bitmap.extend((values[i]<<4)|values[i+1] for i in range(0,len(values),2))
    descriptors.append('{%d,%d,%d,%d,%d,%d}'%(index,round(font.getlength(c)*16),w,h,left,-bottom))
text='''/* Generated by tools/prepare_st_font.py; Noto Sans CJK SC, SIL OFL 1.1. */
#include "lvgl.h"
#include <stdint.h>
'''
text+='static const uint8_t bitmap[] = {'+','.join(map(str,bitmap))+'};\n'
text+='static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {'+','.join(descriptors)+'};\n'
text+='static const uint16_t unicode[] = {'+','.join(str(p-32) for p in points)+'};\n'
text+='''static const lv_font_fmt_txt_cmap_t cmaps[] = {
 { .range_start=32, .range_length=%d, .glyph_id_start=1,
   .unicode_list=unicode, .glyph_id_ofs_list=NULL, .list_length=%d,
   .type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY }
};
static lv_font_fmt_txt_dsc_t font_dsc = {
 .glyph_bitmap=bitmap, .glyph_dsc=glyphs, .cmaps=cmaps,
 .kern_dsc=NULL, .kern_scale=0, .cmap_num=1, .bpp=4,
 .kern_classes=0, .bitmap_format=0
};
const lv_font_t st_font_16 = {
 .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,
 .get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,
 .line_height=21, .base_line=4, .subpx=LV_FONT_SUBPX_NONE,
 .underline_position=-2, .underline_thickness=1, .dsc=&font_dsc
};
'''%(points[-1]-32+1,len(points))
text+='const uint32_t st_font_codepoints[] = {'+','.join(map(str,points))+'};\n'
text+=f'const unsigned st_font_codepoint_count={len(points)};\n'
(ROOT/'assets/fonts/st_font_16.c').write_text(text)
(ROOT/'assets/fonts/st_font_inventory.json').write_text(json.dumps(points)+'\n')
print(f'{len(points)} glyphs; {len(bitmap)} bitmap bytes')
